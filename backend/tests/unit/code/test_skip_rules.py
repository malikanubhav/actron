"""A-AC-31: skip rules classify one example of each reason, and skipped files still get a CodeFile entry."""

from __future__ import annotations

import subprocess
from pathlib import Path

from actron.connectors.code.walk import classify, walk


def test_each_skip_reason() -> None:
    """A-AC-31"""
    assert classify("img/logo.png", b"\x89PNG\r\n") == "binary"
    assert classify("data/blob.dat2", b"abc\x00def") == "binary"
    assert classify("package-lock.json", b"{}") == "lockfile"
    assert classify("Cargo.lock", b"x") == "lockfile"
    assert classify("yarn.lock", b"x") == "lockfile"
    assert classify("static/app.min.js", b"var a=1;") == "minified"
    assert classify("static/app.js", b"var a=1;" * 200) == "minified"
    assert classify("pkg/dist/bundle.js", b"x") == "generated"
    assert classify("node_modules/x/index.js", b"x") == "generated"
    assert classify("gen/api.py", b"# @generated by protoc\nx = 1\n") == "generated"
    assert classify("gen/api.go", b"// Code generated. DO NOT EDIT.\npackage x\n") == "generated"
    assert classify("big.txt", b"a" * 1_000_001) == "too_large"
    assert classify("src/ok.py", b"def f():\n    return 1\n") is None
    assert classify("src/long.py", b"x = '" + b"a" * 2000 + b"'\n") is None  # long lines only matter for js/css


def test_walk_keeps_skipped_files(tmp_path: Path) -> None:
    """A-AC-31"""
    repo = tmp_path / "r"
    repo.mkdir()
    (repo / "a.py").write_text("x = 1\n")
    (repo / "logo.png").write_bytes(b"\x89PNG\x00\x00")
    (repo / "package-lock.json").write_text("{}")
    (repo / "dist").mkdir()
    (repo / "dist" / "out.js").write_text("x")
    subprocess.run(["git", "init", "-q", str(repo)], check=True)
    subprocess.run(["git", "-C", str(repo), "add", "-A"], check=True)
    entries = {e.path: e for e in walk(repo)}
    assert set(entries) == {"a.py", "logo.png", "package-lock.json", "dist/out.js"}
    assert entries["a.py"].stored and entries["a.py"].text == "x = 1\n"
    assert entries["logo.png"].is_skipped and entries["logo.png"].skip_reason == "binary"
    assert entries["logo.png"].text is None and entries["logo.png"].content_hash
    assert entries["package-lock.json"].skip_reason == "lockfile"
    assert entries["dist/out.js"].skip_reason == "generated"
