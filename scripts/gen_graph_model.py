"""Writes docs/graph-model.md from the ontology files: every node with its properties, every link,
node groups with their expansion counts, and the fabric relationships skipped at load time.

Run from the repository root:  uv run --project backend python scripts/gen_graph_model.py
Add --check to fail when the committed document is out of date (used by tests and scripts).
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from actron.graph.ontology import FILE_ORDER, Ontology, load_ontology  # noqa: E402

OUT = ROOT / "docs" / "graph-model.md"
SOURCE_TITLES = {
    "slack": "Slack (fabric file)",
    "linear": "Linear (fabric file)",
    "github": "GitHub",
    "code": "Code and git history",
    "core": "Core (Actron's own nodes and links across sources)",
}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def short(text: str, limit: int = 140) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "..."


def flags(prop: dict[str, Any]) -> str:
    out = []
    if prop.get("required"):
        out.append("required")
    if prop.get("indexed"):
        out.append("indexed")
    if prop.get("unique"):
        out.append("unique")
    if "full-text indexed" in str(prop.get("description", "")):
        out.append("full-text")
    return ", ".join(out)


def render(ontology: Ontology, files: dict[str, dict[str, Any]]) -> str:
    groups: dict[str, list[str]] = files["core"].get("node_groups", {})
    lines: list[str] = []
    add = lines.append

    expanded_by_file = Counter(r.source_file for r in ontology.relationships.values())
    add("# Graph model")
    add("")
    add("Generated by `scripts/gen_graph_model.py` from `ontology/*.json`. Do not edit by hand; the ontology files "
        "are the source of truth and are never changed at runtime.")
    add("")
    add(f"Ontology version: `{ontology.version}`")
    add("")
    add(f"- **{len(ontology.nodes)} node types**, **{len(ontology.relationships)} links** after group expansion.")
    add(f"- {len(ontology.skipped_relationships)} relationships from the Slack and Linear files are skipped at "
        "load time because an endpoint is not a node type (listed at the end).")
    add("- One graph per workspace, named `actron_<workspace>`; one label per node; ids as in spec A, A.C3.")
    add("")
    add("| File | Node types | Declared relationships | Links after expansion |")
    add("|---|---|---|---|")
    for stem in FILE_ORDER:
        data = files[stem]
        add(f"| `{stem}.json` | {len(data['nodes'])} | {len(data.get('relationships', []))} | "
            f"{expanded_by_file[f'{stem}.json']} |")
    add("")

    add("## Common properties")
    add("")
    add("Every node accepts these in addition to its own properties (`core.json`). The graph store writes "
        "`source`, `workspaceId`, `ontologyVersion` and `refreshedAt` on every upsert, and `ingestedAt` on create.")
    add("")
    add("| Property | Type | Flags | Meaning |")
    add("|---|---|---|---|")
    for p in files["core"].get("common_node_properties", []):
        add(f"| `{p['name']}` | {p['type']} | {flags(p)} | {cell(short(p.get('description', '')))} |")
    add("")
    add("Every link accepts these (`core.json`); the store requires `method` and `confidence`.")
    add("")
    add("| Property | Type | Flags | Meaning |")
    add("|---|---|---|---|")
    for p in files["core"].get("common_relationship_properties", []):
        add(f"| `{p['name']}` | {p['type']} | {flags(p)} | {cell(short(p.get('description', '')))} |")
    add("")

    add("## Node groups")
    add("")
    add("A relationship whose endpoint is a group becomes one link type per member.")
    add("")
    add("| Group | Members | Member nodes |")
    add("|---|---|---|")
    for name, members in groups.items():
        add(f"| `{name}` | {len(members)} | {', '.join(f'`{m}`' for m in members)} |")
    add("")

    for stem in FILE_ORDER:
        data = files[stem]
        add(f"## {SOURCE_TITLES[stem]}: `{stem}.json`")
        add("")
        add(f"Version {data.get('version', '?')}. {len(data['nodes'])} node types.")
        add("")
        add("### Nodes")
        add("")
        for node in data["nodes"]:
            props = node.get("properties", [])
            add(f"#### `{node['name']}`")
            add("")
            if node.get("description"):
                add(cell(short(str(node["description"]), 300)))
                add("")
            add(f"Primary key `{node.get('primary_key', 'id')}`, display name `{node.get('display_name', 'name')}`, "
                f"{len(props)} properties.")
            add("")
            add("| Property | Type | Flags | Meaning |")
            add("|---|---|---|---|")
            for p in props:
                add(f"| `{cell(p['name'])}` | {p['type']} | {flags(p)} | {cell(short(p.get('description', '')))} |")
            add("")
        rels = data.get("relationships", [])
        add("### Links")
        add("")
        if not rels:
            add("None declared in this file.")
            add("")
            continue
        add("| Link | From | To | Cardinality | Temporal | Expands to | Allowed properties |")
        add("|---|---|---|---|---|---|---|")
        node_names = {n["name"] for f in files.values() for n in f["nodes"]}
        for r in rels:
            frm, to = r["from_node"], r["to_node"]
            from_members = groups.get(frm, [frm])
            to_members = groups.get(to, [to])
            skipped = any(n not in node_names for n in (*from_members, *to_members))
            count = "skipped" if skipped else str(len(from_members) * len(to_members))
            frm_text = f"`{frm}`" + (f" (group of {len(from_members)})" if frm in groups else "")
            to_text = f"`{to}`" + (f" (group of {len(to_members)})" if to in groups else "")
            allowed = ""
            if not skipped:
                key = (r["name"], from_members[0], to_members[0])
                rel_def = ontology.relationships.get(key)
                if rel_def and rel_def.allowed_properties:
                    allowed = ", ".join(f"`{a}`" for a in sorted(rel_def.allowed_properties))
            add(f"| `{r['name']}` | {frm_text} | {to_text} | {r.get('cardinality', '')} | "
                f"{'yes' if r.get('temporal') else 'no'} | {count} | {allowed} |")
        add("")

    add("## Skipped relationships")
    add("")
    add("Fabric relationships whose endpoint is not a node type. They are reported by `ensure_indexes` "
        "(`IndexReport.skipped_relationships`) and never created.")
    add("")
    add("| File | Link | From | To |")
    add("|---|---|---|---|")
    for file, name, frm, to in sorted(ontology.skipped_relationships):
        add(f"| `{file}` | `{name}` | `{frm}` | `{to}` |")
    add("")
    return "\n".join(lines)


def main() -> int:
    ontology = load_ontology(ROOT / "ontology")
    files = {s: json.loads((ROOT / "ontology" / f"{s}.json").read_text(encoding="utf-8")) for s in FILE_ORDER}
    text = render(ontology, files)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/graph-model.md is out of date; run scripts/gen_graph_model.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(ontology.nodes)} nodes, {len(ontology.relationships)} links")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
