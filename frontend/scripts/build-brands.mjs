// Copies Simple Icons marks into public/brands/ and writes components/brand/simple-paths.ts for inline,
// recolourable rendering. Official marks (Slack, FalkorDB, Pi, TypeSafe) are saved by hand from the owners'
// sites; see public/brands/LICENSES.md. Run: node scripts/build-brands.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsDir = join(root, 'node_modules', 'simple-icons', 'icons')
const dataPath = join(root, 'node_modules', 'simple-icons', 'data', 'simple-icons.json')
const outDir = join(root, 'public', 'brands')
mkdirSync(outDir, { recursive: true })

// Brand marks plus the language marks the build theatre shows next to file paths.
const wanted = {
  github: 'github',
  linear: 'linear',
  python: 'python',
  typescript: 'typescript',
  javascript: 'javascript',
  docker: 'docker',
  temporal: 'temporal',
  mcp: 'modelcontextprotocol',
  clojure: 'clojure',
  json: 'json',
  markdown: 'markdown',
  go: 'go',
  rust: 'rust',
  postgresql: 'postgresql',
  redis: 'redis',
}

let raw = JSON.parse(readFileSync(dataPath, 'utf8'))
const entries = Array.isArray(raw) ? raw : raw.icons
const bySlug = new Map()
for (const entry of entries) {
  const slug =
    entry.slug ??
    entry.title
      .toLowerCase()
      .replace(/\+/g, 'plus')
      .replace(/\./g, 'dot')
      .replace(/&/g, 'and')
      .replace(/[^a-z0-9]/g, '')
  bySlug.set(slug, entry)
}

const paths = {}
for (const [name, slug] of Object.entries(wanted)) {
  const svg = readFileSync(join(iconsDir, `${slug}.svg`), 'utf8')
  const d = /<path d="([^"]+)"/.exec(svg)?.[1]
  const meta = bySlug.get(slug)
  if (!d || !meta) throw new Error(`missing ${slug}`)
  const hex = `#${meta.hex}`
  const title = meta.title
  paths[name] = { title, hex, d, source: meta.source ?? 'https://simpleicons.org', license: meta.license?.type ?? null }
  const coloured = `<svg role="img" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg"><title>${title}</title><path fill="${hex}" d="${d}"/></svg>\n`
  writeFileSync(join(outDir, `${name}.svg`), coloured)
}

const body = `// Generated by scripts/build-brands.mjs from simple-icons ${JSON.parse(readFileSync(join(root, 'node_modules', 'simple-icons', 'package.json'), 'utf8')).version}. Do not edit.
export const SIMPLE_PATHS = ${JSON.stringify(paths, null, 2)} as const

export type SimpleBrand = keyof typeof SIMPLE_PATHS
`
mkdirSync(join(root, 'components', 'brand'), { recursive: true })
writeFileSync(join(root, 'components', 'brand', 'simple-paths.ts'), body)
console.log(`wrote ${Object.keys(paths).length} marks`)
